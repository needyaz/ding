#!/usr/bin/env python3
"""Regenerate the derived spec files from spec/requirements.tsv. Shared by every app; each app vendors this file as
spec/generate.py and adds spec/generate.config.json. Keep the vendored copy identical to the canonical one.

    python3 spec/generate.py          rewrite the derived files in place
    python3 spec/generate.py --check  write nothing; list files that differ, exit 1

Derived: spec/TRACEABILITY.md (whole file) and the marked blocks of spec/BASELINE.md (between
`<!-- BEGIN GENERATED: name -->` and `<!-- END GENERATED: name -->`). Everything outside the markers, and
DRIFT_REPORT.md / PROPOSALS.md, is hand-written and left alone.

spec/generate.config.json:
  prefix         the requirement id prefix, e.g. "UFT" (ids are PREFIX-AREA-NNN)
  areas          object of AREA code -> BASELINE section heading, in document order. A null heading means rows of
                 status US, NI and R go to their own sections whatever their area, and C, IU or X rows are an error.
  evidence_note  one sentence for the TRACEABILITY header saying how evidence paths resolve

Standard library only; deterministic; no network, no timestamps.
"""

import json
import re
import sys
from pathlib import Path

SPEC = Path(__file__).resolve().parent
TSV = SPEC / "requirements.tsv"
TRACE = SPEC / "TRACEABILITY.md"
BASELINE = SPEC / "BASELINE.md"
CONFIG = SPEC / "generate.config.json"
COMMAND = "python3 spec/generate.py"

COLUMNS = ["id", "status", "src", "statement", "evidence"]

# Status code -> label, in table order.
STATUS = {
    "C": "Confirmed",
    "IU": "Implemented, untested",
    "US": "Unspecced behavior",
    "X": "Conflict",
    "NI": "Not implemented",
    "R": "Retired",
}


def fail(msg):
    sys.exit(f"spec/generate.py: {msg}")


def config():
    try:
        cfg = json.loads(CONFIG.read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        fail(f"{CONFIG.name}: cannot read it ({e})")
    for key in ("prefix", "areas", "evidence_note"):
        if key not in cfg:
            fail(f"{CONFIG.name}: missing {key!r}")
    if not re.fullmatch(r"[A-Z]{2,6}", cfg["prefix"]):
        fail(f"{CONFIG.name}: prefix must be 2-6 uppercase letters")
    return cfg


def load(cfg):
    id_re = re.compile(rf"^{re.escape(cfg['prefix'])}-([A-Z]+)-(\d{{3}})$")
    lines = TSV.read_text(encoding="utf-8").split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    if not lines or lines[0].split("\t") != COLUMNS:
        fail(f"{TSV.name}: header must be {COLUMNS}")
    rows, seen = [], set()
    for n, line in enumerate(lines[1:], start=2):
        cells = line.split("\t")
        if len(cells) != len(COLUMNS):
            fail(f"{TSV.name}:{n}: expected {len(COLUMNS)} columns, got {len(cells)}")
        row = dict(zip(COLUMNS, cells))
        m = id_re.match(row["id"])
        if not m:
            fail(f"{TSV.name}:{n}: bad id {row['id']!r}")
        if m.group(1) not in cfg["areas"]:
            fail(f"{TSV.name}:{n}: unknown area {m.group(1)!r}")
        if row["id"] in seen:
            fail(f"{TSV.name}:{n}: duplicate id {row['id']}")
        if row["status"] not in STATUS:
            fail(f"{TSV.name}:{n}: unknown status {row['status']!r}")
        if any("|" in row[k] for k in ("id", "src", "evidence")):
            fail(f"{TSV.name}:{n}: '|' in a table column would break TRACEABILITY.md")
        seen.add(row["id"])
        row["area"] = m.group(1)
        rows.append(row)
    return rows


def counts(rows):
    return {k: sum(r["status"] == k for r in rows) for k in STATUS}


def traceability(rows, cfg):
    c = counts(rows)
    out = [
        "# Traceability",
        "",
        f"Generated by `{COMMAND}` from `requirements.tsv`; do not edit by hand.",
        "",
        "Requirement → status → evidence. " + cfg["evidence_note"] + ' "none" means nothing asserts it; '
        "a code location in brackets is where the behaviour lives.",
        "",
        "| Status | Count |",
        "|---|---|",
    ]
    out += [f"| {label} | {c[k]} |" for k, label in STATUS.items()]
    out += [
        f"| **Total** | **{len(rows)}** |",
        "",
        "| ID | Status | SPEC | Evidence |",
        "|---|---|---|---|",
    ]
    out += [f"| {r['id']} | {STATUS[r['status']]} | {r['src']} | {r['evidence']} |" for r in rows]
    return "\n".join(out) + "\n"


def item(r, marker=""):
    statement = r["statement"]
    if r["status"] == "R" and statement.startswith("Retired:"):
        statement = "_Retired:_" + statement[len("Retired:"):]
    src = "" if r["src"] in ("", "—", "-") else f" _(SPEC {r['src']})_"
    return f"- **{r['id']}** {marker}{statement}{src}"


def baseline_blocks(rows, cfg):
    areas = cfg["areas"]
    c = counts(rows)
    count_line = f"Counts: {len(rows)} requirements — " + ", ".join(
        f"{label} {c[k]}" for k, label in STATUS.items()
    ) + "."

    sections = []
    for area, heading in areas.items():
        if heading is None:
            continue
        items = []
        for r in rows:
            if r["area"] != area or r["status"] not in ("C", "IU", "X"):
                continue
            items.append(item(r, "**[Conflict]** " if r["status"] == "X" else ""))
        if items:
            sections.append(f"## {heading}\n\n" + "\n".join(items))
    unspecced = [item(r, "**[Unspecced behavior]** ") for r in rows if r["status"] == "US"]
    if unspecced:
        sections.append("## Built, not in the old spec\n\n" + "\n".join(unspecced))
    stray = [r["id"] for r in rows if r["status"] in ("C", "IU", "X") and areas[r["area"]] is None]
    if stray:
        fail(f"no BASELINE section for {', '.join(stray)}")

    conflicts = [
        f"- **{r['id']}** — see DRIFT_REPORT; {r['statement']}" for r in rows if r["status"] == "X"
    ] or ["None open."]
    planned = [item(r) for r in rows if r["status"] in ("NI", "R")] or ["None."]

    return {
        "counts": count_line,
        "requirements": "\n\n".join(sections),
        "conflicts": "\n".join(conflicts),
        "planned": "\n".join(planned),
    }


def baseline(rows, cfg, current):
    text = current
    for name, body in baseline_blocks(rows, cfg).items():
        begin, end = f"<!-- BEGIN GENERATED: {name} -->", f"<!-- END GENERATED: {name} -->"
        if text.count(begin) != 1 or text.count(end) != 1:
            fail(f"{BASELINE.name}: needs exactly one {begin} ... {end} pair")
        pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.S)
        text = pattern.sub(lambda _m, b=body: f"{begin}\n{b}\n{end}", text)
    return text


def main(argv):
    if argv not in ([], ["--check"]):
        sys.exit(__doc__)
    check = argv == ["--check"]
    cfg = config()
    rows = load(cfg)
    wanted = {
        TRACE: traceability(rows, cfg),
        BASELINE: baseline(rows, cfg, BASELINE.read_text(encoding="utf-8")),
    }
    stale = []
    for path, text in wanted.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(path)
        if check:
            print(path.relative_to(SPEC.parent))
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if check and stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
